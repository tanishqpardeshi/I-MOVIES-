export const DEFAULT_FALLBACK_POSTER =
  'https://images.unsplash.com/photo-1489599849927-2ee91cede3ba?w=1000&auto=format&fit=crop&q=85';

export function resolveMoviePoster(title, currentUrl) {
  const rawTitle = (title || '').toLowerCase().trim();
  const cleanTitle = rawTitle.replace(/[’']/g, "'");

  // Direct exact match
  if (KNOWN_POSTERS[cleanTitle]) {
    return KNOWN_POSTERS[cleanTitle].local;
  }

  // Normalized substring matches for robust title variations
  if (cleanTitle.includes('pehla pyaar') || cleanTitle.includes('pehla pyar') || cleanTitle.includes('doosri baar') || cleanTitle.includes('dusri baar')) {
    return '/posters/pehla-pyaar-dusri-baar.jpg';
  }
  if (cleanTitle.includes('ramayana')) {
    return '/posters/ramayana.jpg';
  }
  if (cleanTitle.includes('furiosa')) {
    return '/posters/furiosa.jpg';
  }
  if (cleanTitle.includes('singham')) {
    return '/posters/singham-again.jpg';
  }
  if (cleanTitle.includes('pushpa')) {
    return '/posters/pushpa-2.jpg';
  }
  if (cleanTitle.includes('udta teer')) {
    return '/posters/udta-teer.jpg';
  }
  if (cleanTitle.includes('bhool bhulai')) {
    return '/posters/bhool-bhulaiyaa-3.jpg';
  }
  if (cleanTitle.includes('naveli') || cleanTitle.includes('navelli')) {
    return '/posters/nayyi-navelli.jpg';
  }
  if (cleanTitle.includes('chhaava') || cleanTitle.includes('chhava')) {
    return '/posters/chhaava.jpg';
  }
  if (cleanTitle.includes('munjya') || cleanTitle.includes('mujya')) {
    return '/posters/munjya.jpg';
  }
  if (cleanTitle.includes('alien') && cleanTitle.includes('romulus')) {
    return '/posters/alien-romulus.jpg';
  }
  if (cleanTitle.includes('kalki')) {
    return '/posters/kalki-2898-ad.jpg';
  }
  if (cleanTitle.includes('clayface')) {
    return '/posters/clayface.jpg';
  }
  if (cleanTitle === 'hope' || cleanTitle.includes('hope') || cleanTitle.includes('hopeu')) {
    return '/posters/hope.jpg';
  }

  if (currentUrl && (currentUrl.startsWith('/posters/') || currentUrl.startsWith('http://localhost') || currentUrl.startsWith('/'))) {
    return currentUrl;
  }
  if (currentUrl && (currentUrl.includes('wikimedia.org') || currentUrl.includes('wikipedia.org'))) {
    return `/api/images/proxy?url=${encodeURIComponent(currentUrl)}`;
  }
  return currentUrl || DEFAULT_FALLBACK_POSTER;
}

export function getFallbackMoviePoster(title, failedSrc) {
  const cleanTitle = (title || '').toLowerCase().trim().replace(/[’']/g, "'");
  const match = KNOWN_POSTERS[cleanTitle];
  if (match) {
    if (failedSrc === match.local && match.remote) {
      return match.remote;
    }
  }
  if (cleanTitle.includes('pehla pyaar') || cleanTitle.includes('pehla pyar')) {
    return 'https://www.bollywoodhungama.com/wp-content/uploads/2026/09/Pehla-Pyaar.jpg';
  }
  if (cleanTitle.includes('ramayana')) {
    return 'https://image.tmdb.org/t/p/w780/hX94xNPYwazKOVGGqL1GiwMSNuY.jpg';
  }
  if (failedSrc && failedSrc.includes('maxresdefault.jpg')) {
    return failedSrc.replace('maxresdefault.jpg', 'hqdefault.jpg');
  }
  return DEFAULT_FALLBACK_POSTER;
}

